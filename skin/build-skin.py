#!/usr/bin/env python3
"""Build the AO3 skins from archive-neue-skin.template.css. Run:  python3 build-skin.py
Change colours here, never in the generated files.

Outputs (AO3 takes the width / dark-mode condition from the skin's "Media" setting, not from @media in the CSS)
  Public, committed (each is complete on its own; create ONE skin with Media = "only screen and (max-width: 42em)"):
    archive-neue-skin-light.css
    archive-neue-skin-dark.css
  Private, NOT committed (git-ignored; the maintainer's own two-skin setup with a parent skin):
    private/archive-neue-skin-phone.css       Light base.
    private/archive-neue-skin-phone-dark.css  Colour overrides only; its parent skin is the light base."""
import re
from pathlib import Path

HERE = Path(__file__).parent
PHONE_WIDTH = "42em"          # AO3's own "narrow" breakpoint

THEMES = {
    "light": dict(bg="#ffffff", bg2="#f6f6f4", ink="#17171a", muted="#6b6b73",
                  line="#e6e6e8", line2="#cfcfd4", link="#2f54eb"),
    "dark":  dict(bg="#111113", bg2="#19191c", ink="#e9e9ea", muted="#9b9ba3",
                  line="#303036", line2="#4b4b53", link="#8da4f5"),
}

RULE = re.compile(r"([^{}]+)\{([^{}]*)\}")


def fill(template, colours):
    css = template
    for key, value in colours.items():
        css = css.replace("{{" + key + "}}", value)
    assert "{{" not in css, "unfilled placeholder"
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)       # comments out: keeps rule parsing simple


def declarations(body):
    return [d.strip() for d in body.split(";") if d.strip()]


def add_important(css):
    """AO3's own stylesheets (especially the phone one) are specific, so every
    declaration gets !important. Skins are allowed to."""
    def fix(m):
        decls = [d if "!important" in d else d + " !important" for d in declarations(m.group(2))]
        return m.group(1).strip() + " { " + "; ".join(decls) + "; }\n"
    return RULE.sub(fix, css)


def dark_overrides(light, dark):
    """Only the declarations whose value differs between light and dark."""
    lr, dr = RULE.findall(light), RULE.findall(dark)
    assert len(lr) == len(dr)
    out = []
    for (ls, lb), (ds, db) in zip(lr, dr):
        assert ls.strip() == ds.strip()
        diff = [d for l, d in zip(declarations(lb), declarations(db)) if l != d]
        if diff:
            out.append(ls.strip() + " { " + "; ".join(diff) + "; }")
    return "\n".join(out) + "\n"


template = (HERE / "archive-neue-skin.template.css").read_text()
built = {name: add_important(fill(template, c)) for name, c in THEMES.items()}

NOTE = "   Set this skin's Media to ONLY: only screen and (max-width: 42em) */\n"
public = {"light": "/* Archive Neue skin, phone, light. Generated by build-skin.py; edit the template instead.\n" + NOTE,
          "dark": "/* Archive Neue skin, phone, dark. Generated by build-skin.py; edit the template instead.\n" + NOTE}
for name in ("light", "dark"):
    out = HERE / f"archive-neue-skin-{name}.css"
    out.write_text(public[name] + built[name])
    print("wrote", out.name, len(built[name]), "bytes")

private = HERE / "private"
private.mkdir(exist_ok=True)
phone = ("/* Archive Neue skin, phone (light base). Generated by build-skin.py; edit the template instead.\n" + NOTE + built["light"])
dark = ("/* Archive Neue skin, phone dark overrides (colours only). Generated by build-skin.py.\n"
        "   Set this skin's Media to ONLY: only screen and (max-width: 42em), and add the phone skin as its parent. */\n"
        + dark_overrides(built["light"], built["dark"]))
for name, css in (("phone", phone), ("phone-dark", dark)):
    out = private / f"archive-neue-skin-{name}.css"
    out.write_text(css)
    print("wrote private/" + out.name, len(css), "bytes")
